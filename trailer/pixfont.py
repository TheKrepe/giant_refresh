def mask(s, gap=1):
    cols = []
    for ch in s:
        rows = G[ch].split()
        for x in range(len(rows[0])):
            cols.append([rows[y][x] == '1' for y in range(7)])
        cols.extend([[False] * 7] * gap)
    if gap and cols:
        cols = cols[:-gap]
    return np.array(cols, dtype=bool).T  # 7 x W

def width(s, scale, gap=1):
    return mask(s, gap).shape[1] * scale

def stamp(layer, s, x, y, scale, top, bot, outline, shadow=None, gap=1, hi=True):
    """Draws text into an RGBA numpy layer (art pixels). Returns width."""
    m = np.kron(mask(s, gap), np.ones((scale, scale), dtype=bool))
    hh, ww = m.shape
    pad = np.pad(m, 1)
    dil = pad.copy()
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            dil |= np.roll(np.roll(pad, dy, 0), dx, 1)
    if shadow is not None:
        sh = np.zeros_like(dil)
        sh[1 + max(1, scale // 2):, 1 + max(1, scale // 2):] = dil[:-(1 + max(1, scale // 2)), :-(1 + max(1, scale // 2))]
        paint(layer, sh, x - 1, y - 1, shadow)
    paint(layer, dil, x - 1, y - 1, outline)
    rows = np.arange(hh)[:, None]
    split = (7 * scale) // 2
    paint(layer, m & (rows < split), x, y, top)
    paint(layer, m & (rows >= split), x, y, bot)
    if hi:
        edge = m & ~np.roll(m, 1, 0)
        paint(layer, edge, x, y, tuple(min(255, c + 45) for c in top[:3]))
    return ww

def paint(layer, msk, x, y, color):
    ys, xs = np.nonzero(msk)
    ys = ys + y
    xs = xs + x
    ok = (ys >= 0) & (ys < layer.shape[0]) & (xs >= 0) & (xs < layer.shape[1])
    c = tuple(color) + ((255,) if len(color) == 3 else ())
    layer[ys[ok], xs[ok]] = c
